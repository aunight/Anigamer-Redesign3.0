import fs from 'node:fs';
import assert from 'node:assert/strict';
import test from 'node:test';
import {JSDOM} from 'jsdom';

test('membership styling retains native actions and redeem opens a dismissible dialog',async()=>{
  const dom=new JSDOM(`<body><div class="mainmenu"><a href="redeem.php">序號兌換</a></div><div id="BH_background"><div class="container"><div class="pay-state"><div class="usercard"><div class="user-status"><div class="status-info">您目前的方案為 <span class="status-info-program">無廣告版每 30 天自動扣款</span>，最終服務到期日為 2026-12-03 00:52，預定下一期扣款日 2026-12-06 01:52:17。</div></div></div><div id="historyList" class="is-more"></div><div class="list-morebtn">展開全部</div></div><button id="cancel">停用自動扣款</button></div></div></body>`,{url:'https://ani.gamer.com.tw/animePayed.php',runScripts:'outside-only',pretendToBeVisual:true});
  const w=dom.window,d=w.document;
  w.matchMedia=()=>({matches:false,addEventListener(){}});
  w.AbortSignal.timeout=()=>undefined;
  w.fetch=async()=>({ok:true,text:async()=>'<div class="paycard-container"><div class="paycard"><p class="programtitle">無廣告 30 天</p><div class="programoney"><span class="money-main">99</span></div><div class="paychose">請選擇付款方式</div></div><div class="userpaychose" style="display:none"><a href="https://ani.gamer.com.tw/animePay2.php?itemSn=84">信用卡</a></div></div>'});
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
  const native=d.querySelector('.list-morebtn');
  native.addEventListener('click',()=>d.querySelector('#historyList').classList.toggle('is-more'));
  for(const file of ['settings.js','content.js'])w.eval(fs.readFileSync(`src/${file}`,'utf8'));
  assert(d.body.classList.contains('ani-account-page'));
  assert.equal(native.getAttribute('aria-expanded'),'false');
  native.click();await new Promise(r=>setTimeout(r,40));
  assert.equal(native.getAttribute('aria-expanded'),'true','original expand action remains functional');
  assert(native.querySelector('svg'));
  const plans=d.querySelector('.ani-membership-plans');assert(plans,'native plans appear below membership history');
  const payment=plans.querySelector('.ani-payment-trigger');payment.click();assert.equal(payment.getAttribute('aria-expanded'),'true');
  assert.equal(plans.querySelector('.userpaychose a').href,'https://ani.gamer.com.tw/animePay2.php?itemSn=84','payment destination remains native');
  assert(!plans.querySelector('.ani-current-plan [role="tooltip"]'));
  const card=payment.closest('.paycard-container');
  card.dispatchEvent(new w.Event('pointerleave'));
  assert.equal(payment.getAttribute('aria-expanded'),'true');
  payment.click();
  card.dispatchEvent(new w.Event('pointerenter'));
  assert.equal(payment.getAttribute('aria-expanded'),'false');
  payment.click();
  assert(card.classList.contains('ani-methods-open'));
  assert.equal(card.querySelector('.userpaychose').style.display,'flex');
  card.querySelector('.userpaychose').dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  assert(!card.querySelector('.ani-methods-close'));
  assert.equal(payment.getAttribute('aria-expanded'),'false');
  const redeem=d.querySelector('.mainmenu a');
  redeem.dispatchEvent(new w.Event('pointerenter'));
  const preloadedFrame=d.querySelector('#ani-redeem-modal iframe');
  assert(preloadedFrame,'intent preloads the native form');
  assert.equal(d.querySelector('#ani-redeem-modal').open,false);
  redeem.click();
  const modal=d.querySelector('#ani-redeem-modal');assert(modal.open);
  assert.equal(modal.querySelector('iframe').src,'https://ani.gamer.com.tw/redeem.php');
  const form=preloadedFrame.contentDocument;
  form.open();form.write('<html><head><style>.footer-topline{height:2px;background:#333}</style></head><body><div id="BH_background"><div class="container"><div class="redeem-content"><div class="redeem-card"><p class="programtitle">序號兌換</p><p class="redeem-notice">測試說明</p><input class="redeem-key"><button class="redeem-nextbtn">下一步</button></div></div></div></div><div class="footer-topline"></div></body></html>');form.close();
  preloadedFrame.dispatchEvent(new w.Event('load'));
  assert([...form.querySelectorAll('style')].some(s=>s.textContent.includes('footer,.footer-topline,#ani-sort-progress-bar')), 'embedded form receives scoped cleanup for the native footer separator');
  assert(form.querySelector('.programtitle svg'),'ticket icon is added to the actual embedded title');
  modal.querySelector('button').click();assert.equal(modal.open,false);
  redeem.click();assert.equal(modal.querySelector('iframe'),preloadedFrame,'reopening reuses the loaded form rather than loading a new page');
  modal.querySelector('button').click();
  assert.equal(d.querySelectorAll('#cancel').length,1,'subscription action is preserved');
  w.close();
});

